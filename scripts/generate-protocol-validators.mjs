import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const schemaPath = "protocol/schemas/v1.schema.json";
const outputPath = "protocol/generated/v1-schema-validators.ts";
const schemaSource = readFileSync(schemaPath, "utf8");
const schema = JSON.parse(schemaSource);
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { source: true, esm: true, lines: true },
});
ajv.addSchema(schema);

const validators = standaloneCode(ajv, {
  validateRepositoryDescriptorSchema: `${schema.$id}#/$defs/RepositoryDescriptor`,
  validateConfigTreeSchema: `${schema.$id}#/$defs/ConfigTree`,
  validateChangeChunkSchema: `${schema.$id}#/$defs/ChangeChunk`,
  validateCommitSchema: `${schema.$id}#/$defs/Commit`,
});
const schemaHash = createHash("sha256").update(schemaSource, "utf8").digest("hex");
const output = `// @ts-nocheck
// Generated by scripts/generate-protocol-validators.mjs. Do not edit.
// v1.schema.json SHA-256: ${schemaHash}
${validators.trimEnd()}
`;

if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== output) {
    throw new Error(`${outputPath} is stale; run npm run generate:protocol`);
  }
} else {
  mkdirSync("protocol/generated", { recursive: true });
  writeFileSync(outputPath, output, "utf8");
}
