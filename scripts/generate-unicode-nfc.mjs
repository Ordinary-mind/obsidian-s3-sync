import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const sourceDirectory = "scripts/unicode-source/15.1.0";
const unicodeData = readFileSync(`${sourceDirectory}/UnicodeData.txt`, "utf8");
const exclusionsData = readFileSync(`${sourceDirectory}/CompositionExclusions.txt`, "utf8");
const canonicalDecomposition = {};
const canonicalCombiningClass = {};

for (const line of unicodeData.split(/\r?\n/)) {
  if (!line) continue;
  const fields = line.split(";");
  const codePoint = Number.parseInt(fields[0], 16);
  const combiningClass = Number.parseInt(fields[3], 10);
  if (combiningClass !== 0) canonicalCombiningClass[codePoint] = combiningClass;
  const decomposition = fields[5];
  if (decomposition && !decomposition.startsWith("<")) {
    canonicalDecomposition[codePoint] = decomposition.split(" ").map((value) => Number.parseInt(value, 16));
  }
}

const exclusions = new Set(
  exclusionsData
    .split(/\r?\n/)
    .map((line) => line.replace(/#.*/, "").trim())
    .filter(Boolean)
    .map((value) => Number.parseInt(value, 16)),
);
const canonicalComposition = {};
for (const [codePoint, decomposition] of Object.entries(canonicalDecomposition)) {
  if (decomposition.length === 2 && !exclusions.has(Number(codePoint))) {
    canonicalComposition[`${decomposition[0]}:${decomposition[1]}`] = Number(codePoint);
  }
}

const sourceHash = createHash("sha256")
  .update(unicodeData, "utf8")
  .update(exclusionsData, "utf8")
  .digest("hex");
const output = `// Generated by scripts/generate-unicode-nfc.mjs. Do not edit.\n// Source: Unicode 15.1.0 UnicodeData.txt and CompositionExclusions.txt.\n// Combined input SHA-256: ${sourceHash}\nexport const unicode151CanonicalDecomposition: Readonly<Record<number, readonly number[]>> = Object.freeze(${JSON.stringify(canonicalDecomposition)});\nexport const unicode151CanonicalCombiningClass: Readonly<Record<number, number>> = Object.freeze(${JSON.stringify(canonicalCombiningClass)});\nexport const unicode151CanonicalComposition: Readonly<Record<string, number>> = Object.freeze(${JSON.stringify(canonicalComposition)});\n`;

mkdirSync("protocol/unicode/15.1.0", { recursive: true });
writeFileSync("protocol/unicode/15.1.0/nfc.ts", output, "utf8");
