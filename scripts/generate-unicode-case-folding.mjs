import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";

import common from "@unicode/unicode-15.1.0/Case_Folding/C/symbols.js";
import full from "@unicode/unicode-15.1.0/Case_Folding/F/symbols.js";

const mappings = new Map([...common, ...full]);
const entries = [...mappings.entries()].sort(([left], [right]) =>
  left.codePointAt(0) - right.codePointAt(0),
);
const json = JSON.stringify(Object.fromEntries(entries));
const sourceHash = createHash("sha256").update(json, "utf8").digest("hex");
const output = `// Generated by scripts/generate-unicode-case-folding.mjs. Do not edit.\n// Source: Unicode 15.1.0 CaseFolding.txt C/F via @unicode/unicode-15.1.0@1.6.17 (MIT).\n// Upstream CaseFolding.txt SHA-256: 4e55acfdc32825a22e87670e9056a3bf94ad7c5400065778e9e10f8314372bcf\n// Mapping JSON SHA-256: ${sourceHash}\nexport const unicode151CaseFolding: Readonly<Record<string, string>> = Object.freeze(${json});\n`;

mkdirSync("protocol/unicode/15.1.0", { recursive: true });
writeFileSync("protocol/unicode/15.1.0/case-folding.ts", output, "utf8");
